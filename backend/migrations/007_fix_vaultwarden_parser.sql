-- ^\[...\]\[...\]\[...\]\s+(?<message>.*?)(?:\s+for\s+...)?(?:...)?...$ (a lazy
-- body followed by optional groups that can each match the same text), is
-- ReDoS-vulnerable: polynomial, degree 2. One 55 KB line took 17.5 s on the
-- event loop, blocking syslog ingestion, and V8's linear fallback does not cut
-- polynomial blowups. Because it re-ran on every start, reinstalling the safe
-- catalog version only lasted until the next restart, and the startup regex
-- scan kept warning about it.
--
-- The vaultwarden-access parser now comes from the catalog
-- (cladkins/siembox-catalog, mirrored to catalog/parsers/), whose pattern is
-- linear. Existing installs: Parsers -> Browse Catalog -> install
-- vaultwarden-access (it updates the stored parser by name). This migration
-- never touches it again.
--
-- Left as a no-op rather than deleted so the filename ordering stays stable
-- (same as 009).
