// Bundles the shipper-side discovery agent into ./discovery-agent.js, a single
// standalone CommonJS file the managed shipper runs with Node.
//
// WHY A COMMITTED BUNDLE: the shipper image is built with `context: ./log-shipper`
// (see .github/workflows/build-containers.yml), so its Docker build can't reach
// backend/src to compile the agent itself. We therefore bundle here and commit
// the result; the Dockerfile just COPYs it. The agent's probe core is shared
// with the backend (backend/.../probePipeline.ts + passiveDiscovery/
// activeDiscovery), so REGENERATE AND COMMIT discovery-agent.js whenever that
// probe code changes:
//
//   node log-shipper/build-discovery-agent.mjs
//
// esbuild is resolved from backend/node_modules (no deps added to the shipper).
import { createRequire } from 'module';
import { fileURLToPath } from 'url';
import path from 'path';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const backendDir = path.join(__dirname, '..', 'backend');
const require = createRequire(path.join(backendDir, 'package.json'));
const esbuild = require('esbuild');

// Replace the backend winston logger with the stderr shim so the bundle stays
// dependency-free. passiveDiscovery imports it as a relative `../../utils/logger`.
const loggerShimPlugin = {
  name: 'logger-shim',
  setup(build) {
    build.onResolve({ filter: /utils\/logger$/ }, () => ({
      path: path.join(__dirname, 'discovery-agent', 'logger-shim.ts'),
    }));
  },
};

await esbuild.build({
  entryPoints: [path.join(__dirname, 'discovery-agent', 'index.ts')],
  outfile: path.join(__dirname, 'discovery-agent.js'),
  bundle: true,
  platform: 'node',
  target: 'node18',
  format: 'cjs',
  banner: {
    js: '// GENERATED by log-shipper/build-discovery-agent.mjs -- do not edit by hand.\n// Regenerate after changing the discovery probe code (see that script).',
  },
  plugins: [loggerShimPlugin],
  logLevel: 'info',
});

console.log('Wrote log-shipper/discovery-agent.js');
